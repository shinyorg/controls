// SPIKE (Phase 0 of docs/agui-plan.md): host an IChatClient as an AG-UI endpoint with the official
// AGUI.Server SDK, record each scenario's raw SSE stream as a fixture, and compare what the raw event
// stream carries against what survives AGUIChatClient's IChatClient flattening.
//
//   dotnet run                -> record fixtures + write fixtures/REPORT.md
//   dotnet run -- serve       -> just host http://localhost:5299/agent
using System.Runtime.CompilerServices;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using AGUI.Abstractions;
using AGUI.Client;
using AGUI.Formatting;
using AGUI.Server;
using Microsoft.AspNetCore.Builder;
using Microsoft.Extensions.AI;

var json = new JsonSerializerOptions(JsonSerializerDefaults.Web)
{
    TypeInfoResolver = System.Text.Json.Serialization.Metadata.JsonTypeInfoResolver.Combine(
        AGUIJsonUtilities.DefaultTypeInfoResolver,
        AIJsonUtilities.DefaultOptions.TypeInfoResolver!)
};
AGUIJsonUtilities.RegisterInterruptContentTypes(json);

var serveOnly = args.Contains("serve");
ScriptedChatClient.UniqueIds = serveOnly;
var builder = WebApplication.CreateSlimBuilder();
builder.WebHost.UseUrls(serveOnly ? "http://localhost:5299" : "http://127.0.0.1:0");
builder.Logging.SetMinimumLevel(LogLevel.Warning);
var app = builder.Build();

// The samples call this from a browser (Blazor WebAssembly), so answer CORS for any origin. Spike only.
app.Use(async (http, next) =>
{
    http.Response.Headers.AccessControlAllowOrigin = "*";
    http.Response.Headers.AccessControlAllowHeaders = "*";
    http.Response.Headers.AccessControlAllowMethods = "POST, OPTIONS";
    if (HttpMethods.IsOptions(http.Request.Method))
    {
        http.Response.StatusCode = StatusCodes.Status204NoContent;
        return;
    }
    await next(http);
});

app.MapPost("/agent", async (HttpContext http) =>
{
    var input = await JsonSerializer.DeserializeAsync<RunAgentInput>(http.Request.Body, json, http.RequestAborted)
                ?? throw new InvalidOperationException("no input");

    var streamOptions = new AGUIStreamOptions()
        // backend tool whose result becomes shared state
        .MapResultAsStateSnapshot("update_cart")
        // backend tool whose result is an A2UI surface, carried as an activity
        .MapResult("render_ui", r => [new ActivitySnapshotEvent
        {
            // the @ag-ui/a2ui-middleware convention: one snapshot per surface message, replace = true
            MessageId = "ui-" + r.CallId,
            ActivityType = "a2ui-surface",
            Replace = true,
            Content = JsonSerializer.SerializeToElement(new JsonObject
            {
                ["a2ui_operations"] = JsonNode.Parse((r.Result is JsonElement e ? e : JsonSerializer.SerializeToElement(r.Result, json)).GetRawText())
            }, json)
        }]);

    var ctx = input.ToChatRequestContext(json, streamOptions);
    IChatClient chat = new FunctionInvokingChatClient(new ScriptedChatClient());
    ctx.ChatOptions.Tools = [.. ctx.ChatOptions.Tools ?? [], .. ScriptedChatClient.BackendTools];

    var events = chat
        .GetStreamingResponseAsync(ctx.Messages, ctx.ChatOptions, http.RequestAborted)
        .AsAGUIEventStreamAsync(ctx, http.RequestAborted);

    http.Response.ContentType = SseEventStreamFormatter.ServerSentEventsMediaType;
    await new SseEventStreamFormatter().WriteAsync(events, http.Response.Body, http.RequestAborted);
});

if (serveOnly)
{
    await app.RunAsync();
    return;
}

await app.StartAsync();
var baseUrl = app.Services.GetRequiredService<Microsoft.AspNetCore.Hosting.Server.IServer>()
    .Features.Get<Microsoft.AspNetCore.Hosting.Server.Features.IServerAddressesFeature>()!.Addresses.First().TrimEnd('/') + "/";
var outDir = Path.Combine(AppContext.BaseDirectory, "../../../fixtures");
Directory.CreateDirectory(outDir);
using var http = new HttpClient { BaseAddress = new Uri(baseUrl) };
var report = new StringBuilder("# AG-UI spike report\n\nGenerated by `spikes/AgUiSpike`. Server: AGUI.Server 1.0.1 over a scripted `IChatClient` (+ `FunctionInvokingChatClient`).\n\n");

foreach (var scenario in ScriptedChatClient.Scenarios)
{
    var input = new RunAgentInput
    {
        ThreadId = "thread-1",
        RunId = "run-" + scenario,
        Messages = scenario == "frontend-tool-followup"
            ? [
                new AGUIUserMessage { Id = "u1", Content = new AGUIContent("frontend-tool") },
                new AGUIAssistantMessage
                {
                    Id = "m1",
                    Content = "Let me ask you for dates.",
                    ToolCalls = [new AGUIToolCall { Id = "call-fe-1", Type = "function", Function = new AGUIToolCallFunction { Name = "pick_date_range", Arguments = "{\"min\":\"2026-11-01\",\"max\":\"2026-12-31\"}" } }]
                },
                new AGUIToolMessage { Id = "t1", ToolCallId = "call-fe-1", Content = new AGUIContent("{\"start\":\"2026-11-10\",\"end\":\"2026-11-14\"}") }
              ]
            : [new AGUIUserMessage { Id = "u1", Content = new AGUIContent(scenario) }],
        Tools = scenario is "frontend-tool" or "frontend-tool-followup"
            ? [new AGUITool
              {
                  Name = "pick_date_range",
                  Description = "Ask the user to choose a date range",
                  Parameters = JsonDocument.Parse("""{"type":"object","properties":{"min":{"type":"string"},"max":{"type":"string"}}}""").RootElement
              }]
            : [],
    };

    // 1. raw wire bytes -> fixture
    using var req = new HttpRequestMessage(HttpMethod.Post, "/agent")
    {
        Content = new StringContent(JsonSerializer.Serialize(input, json), Encoding.UTF8, "application/json")
    };
    req.Headers.Accept.ParseAdd(SseEventStreamFormatter.ServerSentEventsMediaType);
    using var res = await http.SendAsync(req, HttpCompletionOption.ResponseHeadersRead);
    var raw = await res.Content.ReadAsStringAsync();
    await File.WriteAllTextAsync(Path.Combine(outDir, scenario + ".sse"), raw);

    // 2. raw events as the SDK decodes them
    var rawEvents = new List<BaseEvent>();
    await foreach (var e in new SseEventStreamFormatter().ReadAsync(new MemoryStream(Encoding.UTF8.GetBytes(raw)), default))
        rawEvents.Add(e);

    // 3. the same run through AGUIChatClient (IChatClient view)
    var client = new AGUIChatClient(new AGUIChatClientOptions(new HttpClient { BaseAddress = new Uri(baseUrl) }, baseUrl + "agent"));
    var updates = new List<string>();
    try
    {
        var options = new ChatOptions();
        if (input.Tools.Count > 0)
            options.Tools = [AIFunctionFactory.CreateDeclaration("pick_date_range", "Ask the user to choose a date range", input.Tools[0].Parameters!.Value)];
        await foreach (var u in client.GetStreamingResponseAsync(input.Messages.AsChatMessages(), options))
        {
            var contents = string.Join(", ", u.Contents.Select(c => c.GetType().Name));
            var props = u.AdditionalProperties is { Count: > 0 } ap ? " props=[" + string.Join(",", ap.Keys) + "]" : "";
            var rawRep = u.RawRepresentation is BaseEvent be ? " raw=" + be.Type : u.RawRepresentation is null ? "" : " raw=" + u.RawRepresentation.GetType().Name;
            updates.Add($"{(contents.Length == 0 ? "(no content)" : contents)}{props}{rawRep}{(u.FinishReason is { } f ? " finish=" + f : "")}");
        }
    }
    catch (Exception ex)
    {
        updates.Add("THREW " + ex.GetType().Name + ": " + ex.Message);
    }

    report.Append($"## `{scenario}`\n\n**Raw events ({rawEvents.Count}):** ")
          .AppendJoin(" → ", rawEvents.Select(e => e.Type))
          .Append("\n\n**AGUIChatClient updates (" + updates.Count + "):**\n\n")
          .AppendJoin("\n", updates.Select(u => "- " + u))
          .Append("\n\n");
}

await File.WriteAllTextAsync(Path.Combine(outDir, "REPORT.md"), report.ToString());
Console.WriteLine(report);
await app.StopAsync();


/// <summary>Deterministic IChatClient: the last user message picks the script.</summary>
sealed class ScriptedChatClient : IChatClient
{
    // serve mode: real clients hold whole conversations, so ids must not repeat across runs (recorded fixtures keep stable ids)
    public static bool UniqueIds;

    public static readonly string[] Scenarios = ["text", "reasoning", "frontend-tool", "frontend-tool-followup", "backend-state", "a2ui", "interrupt", "error"];

    public static readonly AITool[] BackendTools =
    [
        AIFunctionFactory.Create(
            () => JsonDocument.Parse("""{"cart":{"items":[{"sku":"A1","qty":2}],"total":19.98}}""").RootElement,
            "update_cart", "Updates the cart"),
        AIFunctionFactory.Create(
            () => JsonDocument.Parse("""
                [{"version":"1.0","createSurface":{"surfaceId":"s1","catalogId":"https://a2ui.org/specification/v1_0/catalogs/basic/catalog.json","dataModel":{"name":"Allan"},
                  "components":[{"id":"root","component":"Column","children":["t","b"]},
                                {"id":"t","component":"Text","text":{"@path":"/name"}},
                                {"id":"b","component":"Button","child":"bl","action":{"event":{"name":"confirm","context":{"who":{"@path":"/name"}}}}},
                                {"id":"bl","component":"Text","text":"Confirm"}]}}]
                """).RootElement,
            "render_ui", "Renders an A2UI surface")
    ];

    public async IAsyncEnumerable<ChatResponseUpdate> GetStreamingResponseAsync(
        IEnumerable<ChatMessage> messages, ChatOptions? options = null, [EnumeratorCancellation] CancellationToken ct = default)
    {
        var list = messages.ToList();
        var scenario = list.LastOrDefault(m => m.Role == ChatRole.User)?.Text ?? "text";
        var afterTool = list.LastOrDefault()?.Role == ChatRole.Tool;
        // unique per response: ids that repeat across runs would merge into earlier messages on the client
        var msgId = UniqueIds ? "m-" + Guid.NewGuid().ToString("N")[..8] : "m" + list.Count;

        ChatResponseUpdate U(params AIContent[] c) => new(ChatRole.Assistant, c) { MessageId = msgId };
        string Call(string id) => UniqueIds ? id + "-" + Guid.NewGuid().ToString("N")[..6] : id;

        if (afterTool)
        {
            foreach (var w in Words("Done — that's updated."))
                yield return U(new TextContent(w));
            yield break;
        }

        switch (scenario)
        {
            case "reasoning":
                foreach (var w in Words("The user wants a greeting. Keep it short."))
                    yield return U(new TextReasoningContent(w));
                yield return U(new TextReasoningContent(null) { ProtectedData = "ENCRYPTED-BLOB" });
                foreach (var w in Words("Hello there!"))
                    yield return U(new TextContent(w));
                break;

            case "frontend-tool":
                yield return U(new TextContent("Let me ask you for dates."));
                yield return U(new FunctionCallContent(Call("call-fe-1"), "pick_date_range",
                    new Dictionary<string, object?> { ["min"] = "2026-11-01", ["max"] = "2026-12-31" }));
                break;

            case "backend-state":
                yield return U(new FunctionCallContent(Call("call-be-1"), "update_cart", new Dictionary<string, object?>()));
                break;

            case "a2ui":
                yield return U(new FunctionCallContent(Call("call-ui-1"), "render_ui", new Dictionary<string, object?>()));
                break;

            case "interrupt":
                yield return U(new TextContent("I need approval to place the order."));
                yield return U(new InterruptRequestContent("int-1")
                {
                    Reason = "approval",
                    Message = "Place order for $19.98?",
                    ResponseSchema = JsonDocument.Parse("""{"type":"object","properties":{"approved":{"type":"boolean"}}}""").RootElement
                });
                break;

            case "error":
                yield return U(new TextContent("Starting…"));
                throw new InvalidOperationException("Model exploded");

            default:
                foreach (var w in Words("Hi! **Markdown** works, and so does `code`.\n\n- one\n- two"))
                    yield return U(new TextContent(w));
                break;
        }
        await Task.CompletedTask;
    }

    static IEnumerable<string> Words(string s)
    {
        var parts = s.Split(' ');
        for (var i = 0; i < parts.Length; i++)
            yield return i == parts.Length - 1 ? parts[i] : parts[i] + " ";
    }

    public Task<ChatResponse> GetResponseAsync(IEnumerable<ChatMessage> messages, ChatOptions? options = null, CancellationToken ct = default)
        => GetStreamingResponseAsync(messages, options, ct).ToChatResponseAsync(ct);

    public object? GetService(Type serviceType, object? serviceKey = null) => serviceType.IsInstanceOfType(this) ? this : null;
    public void Dispose() { }
}
